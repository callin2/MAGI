"""Preserve this turn's Windows legacy recheck separately; restore historical reports."""
import hashlib,json,subprocess
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
OUT=ROOT/'experiments/effectiveness-20261018/legacy-windows-recheck'
def h(b):return hashlib.sha256(b).hexdigest()
rows=[]
for run in (ROOT/'experiments/recursive-work/runs').iterdir():
    if not (run/'state.json').exists():continue
    state=json.loads((run/'state.json').read_text(encoding='utf-8'));seen=set()
    for issue in state['issues']:
        for e in issue.get('evidence',[]):
            path=run/e['path'];relative=path.relative_to(ROOT).as_posix()
            if relative in seen:continue
            seen.add(relative)
            blob=subprocess.check_output(['git','show','HEAD:'+relative],cwd=ROOT)
            rows.append({'path':relative,'recorded':e['sha256'],'checkout':h(path.read_bytes()),'git_blob':h(blob)})
OUT.mkdir(parents=True,exist_ok=True)
(OUT/'byte-audit.json').write_text(json.dumps(rows,indent=2)+'\n',encoding='utf-8')
names=subprocess.check_output(['git','diff','--name-only','--','experiments/recursive-work'],cwd=ROOT,text=True).splitlines()
for name in names:
    if not name.startswith('experiments/recursive-work/') or not (name.endswith('evaluation.json') or name.endswith('evaluation-recheck.json') or name.endswith('/results.json')):
        raise RuntimeError('Not a report generated by this recheck: '+name)
    target=OUT/Path(name).relative_to('experiments/recursive-work');target.parent.mkdir(parents=True,exist_ok=True)
    target.write_bytes((ROOT/name).read_bytes())
if names:subprocess.run(['git','restore','--',*names],cwd=ROOT,check=True)
print(json.dumps({'reports_preserved':len(names),'artifacts_audited':len(rows),'match_recorded_git_blob':sum(r['recorded']==r['git_blob'] for r in rows),'match_checkout':sum(r['recorded']==r['checkout'] for r in rows)}))
